/**
 * Jizao platform element-bridge: bridges element-selection interactions between the iframe and the parent page.
 *
 * Current loading mechanism: ships with the template scaffold into the sandbox workspace's
 * public/ and is referenced by the template's app/layout.tsx via a synchronous <script> in
 * <head>. It is therefore visible, editable, and deletable by users/agents — it is a
 * best-effort capability: if the script is gone, only element selection stops working;
 * the preview itself is unaffected.
 *
 * Responsibilities:
 *  - Receive __jizao_toggle_select_mode messages from the parent page and toggle selection mode
 *  - In active mode, highlight the element under the cursor on hover (collapse when the mouse leaves the page), click to select/deselect
 *  - Show the element tagName at the top-left of the highlight box, on both hover and selection boxes
 *  - Report selection information to the parent page via postMessage
 *  - Multi-select accumulates: clicking a new element adds it, clicking a selected one removes it; the two are independent
 *  - Esc clears all selections; the parent page can command removal of a single selection
 *
 * dataSourceId is not generated by this script: jizao-source-loader injects the stable
 * data-source-id into JSX elements in the user's source at build time; this script only reads and forwards it.
 * Elements without the attribute (third-party component output, portals, files the loader
 * did not cover, etc.) do not participate in selection: no highlight, not clickable.
 *
 * Security constraints:
 *  - postMessage uses an explicit targetOrigin, never "*": messages are not broadcast.
 *  - The whole file follows "fail silently": every exception is swallowed and must never affect the user app.
 */
(function () {
  "use strict";

  // Guard against duplicate loading (HMR / manual double-injection)
  if (window.__JIZAO_ELEMENT_BRIDGE__) return;
  window.__JIZAO_ELEMENT_BRIDGE__ = true;

  // Do not initialize outside an iframe
  if (!window.parent || window.parent === window) return;

  /**
   * Derives the parent window origin from document.referrer / ancestorOrigins.
   * Returns null on failure — callers must give up sending.
   */
  function resolveParentOrigin() {
    try {
      if (document.referrer) {
        return new URL(document.referrer).origin;
      }
    } catch (_e) {
      /* Failed to parse referrer; fall through to ancestorOrigins */
    }

    try {
      if (window.location.ancestorOrigins && window.location.ancestorOrigins.length > 0) {
        return window.location.ancestorOrigins[0];
      }
    } catch (_e) {
      /* ancestorOrigins unavailable (old Firefox, etc.); degrade to null */
    }

    return null;
  }

  var parentOrigin = resolveParentOrigin();

  // Parent page origin cannot be determined; fail silently
  if (!parentOrigin) return;

  // Brand accent colors for the selection UI. The sandbox image build fills in these
  // placeholders from templates/nextjs/variants: purple domestically, green overseas.
  var ACCENT_COLOR = "__TEMPLATE_ACCENT_COLOR__";
  var ACCENT_INK = "__TEMPLATE_ACCENT_INK__";

  // ========== Utilities ==========

  /**
   * Whether an element is injected by jizao itself (highlight boxes, etc.); such elements must be excluded.
   */
  function isJizaoElement(el) {
    if (!el) return true;
    // Walk up and check whether an id or class starts with jizao
    var node = el;
    while (node && node.nodeType === 1) {
      var id = node.id || "";
      if (id.indexOf("jizao-") === 0) return true;
      var cls = node.className;
      if (typeof cls === "string" && cls.indexOf("jizao-") >= 0) return true;
      node = node.parentNode;
    }
    return false;
  }

  /**
   * Whether an element is selectable: not a jizao-injected element and carrying a build-time-injected data-source-id.
   * Elements without an id (DOM created imperatively by third-party components, portals,
   * files the loader did not cover, etc.) do not participate in selection.
   */
  function isSelectable(el) {
    return !!el && !isJizaoElement(el) && !!(el.dataset && el.dataset.sourceId);
  }

  /**
   * Generates a CSS selector for an element: prefer id, then tag + nth-of-type path
   */
  function generateSelector(el) {
    if (!el || el.nodeType !== 1) return "";

    var parts = [];
    var node = el;

    while (node && node.nodeType === 1 && node.tagName !== "HTML") {
      var part = node.tagName.toLowerCase();

      // An id is globally unique, so use it and stop immediately
      if (node.id) {
        part += "#" + node.id;
        parts.unshift(part);
        break;
      }

      // Compute nth-of-type
      if (node.parentNode) {
        var siblings = node.parentNode.children;
        var count = 0;
        var index = 0;
        for (var i = 0; i < siblings.length; i++) {
          if (siblings[i].tagName === node.tagName) {
            count++;
            if (siblings[i] === node) {
              index = count;
            }
          }
        }
        if (count > 1) {
          part += ":nth-of-type(" + index + ")";
        }
      }

      parts.unshift(part);
      node = node.parentNode;
    }

    // Prefix with body
    parts.unshift("body");

    return parts.join(" > ");
  }

  /**
   * Extracts source-location information from the element's dataset
   */
  function getSourceInfo(el) {
    var info = {};
    if (!el || !el.dataset) return info;
    if (el.dataset.sourceFile) info.sourceFile = el.dataset.sourceFile;
    if (el.dataset.sourceLine) info.sourceLine = parseInt(el.dataset.sourceLine, 10);
    if (el.dataset.sourceCol) info.sourceCol = parseInt(el.dataset.sourceCol, 10);
    return info;
  }

  /**
   * Extracts the element's text content (truncated to 50 characters)
   */
  function getTextContent(el) {
    var text = (el.textContent || "").trim();
    if (text.length > 50) {
      text = text.substring(0, 50) + "...";
    }
    return text;
  }

  /**
   * Gets the className string
   */
  function getClassName(el) {
    var cls = el.className;
    if (typeof cls === "string") return cls;
    if (cls && cls.baseVal != null) return cls.baseVal; // SVG className is an SVGAnimatedString
    return "";
  }

  /**
   * Sends a message to the parent page
   */
  function sendToParent(data) {
    try {
      window.parent.postMessage(data, parentOrigin);
    } catch (_e) {
      /* Swallow postMessage errors */
    }
  }

  // ========== State ==========

  var isActive = false; // Whether selection mode is on
  var selectedElements = {}; // dataSourceId -> { element, overlay }, multi-select accumulates
  var hoverOverlay = null; // Hover highlight box
  var overlayContainer = null; // Highlight box container
  var styleElement = null; // Injected stylesheet
  var currentHoverElement = null; // Currently hovered element

  /**
   * Injects the stylesheet
   */
  function injectStyles() {
    if (styleElement) return;
    try {
      styleElement = document.createElement("style");
      styleElement.id = "jizao-inspector-styles";
      styleElement.textContent = [
        "#jizao-inspector-overlay {",
        "  position: fixed;",
        "  top: 0;",
        "  left: 0;",
        "  right: 0;",
        "  bottom: 0;",
        "  pointer-events: none;",
        "  z-index: 2147483647;",
        "}",
        ".jizao-highlight-box {",
        "  position: absolute;",
        "  pointer-events: none;",
        "  box-sizing: border-box;",
        "}",
        ".jizao-hover-box {",
        "  border: 2px dashed " + ACCENT_COLOR + ";",
        "  background: " + ACCENT_COLOR + "1a;",
        "}",
        ".jizao-selected-box {",
        "  border: 2px solid " + ACCENT_COLOR + ";",
        "  background: " + ACCENT_COLOR + "26;",
        "}",
        ".jizao-tag-label {",
        "  position: absolute;",
        "  left: -2px;",
        "  bottom: calc(100% + 2px);",
        "  padding: 0 4px;",
        "  border-radius: 2px 2px 0 0;",
        "  background: " + ACCENT_COLOR + ";",
        "  color: " + ACCENT_INK + ";",
        "  font-family: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace;",
        "  font-size: 11px;",
        "  line-height: 16px;",
        "  white-space: nowrap;",
        "  pointer-events: none;",
        "}",
        // When the element hugs the viewport top the label would be clipped, so flip it inside the box
        ".jizao-tag-label-inside {",
        "  top: 0;",
        "  bottom: auto;",
        "  border-radius: 0 0 2px 0;",
        "}",
      ].join("\n");
      document.head.appendChild(styleElement);
    } catch (_e) {
      /* Style injection failed */
    }
  }

  /**
   * Gets or creates the overlay container
   */
  function getOverlayContainer() {
    if (overlayContainer) return overlayContainer;
    try {
      overlayContainer = document.createElement("div");
      overlayContainer.id = "jizao-inspector-overlay";
      document.body.appendChild(overlayContainer);
    } catch (_e) {
      /* Failed to create the container */
    }
    return overlayContainer;
  }

  /**
   * When the element is within this distance of the viewport top, the tagName label flips
   * inside the box to avoid being clipped by the viewport
   */
  var LABEL_FLIP_TOP = 20;

  /**
   * Updates the highlight box position from the element's bounding rect.
   *
   * The label is a child of the box and moves with it, so here we only decide whether it
   * sits above the box or inside it.
   */
  function updateBoxPosition(box, rect) {
    box.style.left = rect.left + "px";
    box.style.top = rect.top + "px";
    box.style.width = rect.width + "px";
    box.style.height = rect.height + "px";

    var label = box.querySelector(".jizao-tag-label");
    if (!label) return;
    if (rect.top < LABEL_FLIP_TOP) {
      label.classList.add("jizao-tag-label-inside");
    } else {
      label.classList.remove("jizao-tag-label-inside");
    }
  }

  /**
   * Creates the tagName label at the top-left of a highlight box
   */
  function createTagLabel(tagName) {
    var label = document.createElement("span");
    label.className = "jizao-tag-label";
    label.textContent = tagName;
    return label;
  }

  /**
   * Creates a highlight box element with the element tagName at its top-left
   */
  function createHighlightBox(className, tagName) {
    var box = document.createElement("div");
    box.className = "jizao-highlight-box " + className;
    box.appendChild(createTagLabel(tagName));
    return box;
  }

  /**
   * Updates the hover highlight
   */
  function updateHover(element) {
    if (!isActive) return;

    // The mouse is over no element (e.g. moved outside the viewport) -> collapse the dashed box
    if (!element) {
      hideHover();
      return;
    }

    if (element === currentHoverElement) return;

    // Only highlight selectable elements (exclude jizao's own elements and elements without data-source-id)
    if (!isSelectable(element)) {
      hideHover();
      return;
    }

    currentHoverElement = element;

    if (!hoverOverlay) {
      var container = getOverlayContainer();
      if (!container) return;
      hoverOverlay = createHighlightBox("jizao-hover-box", element.tagName.toLowerCase());
      container.appendChild(hoverOverlay);
    } else {
      // The hover box reuses one node; when switching elements only the label text changes
      var hoverLabel = hoverOverlay.querySelector(".jizao-tag-label");
      if (hoverLabel) hoverLabel.textContent = element.tagName.toLowerCase();
    }

    var rect = element.getBoundingClientRect();
    updateBoxPosition(hoverOverlay, rect);
    hoverOverlay.style.display = "block";
  }

  /**
   * Hides the hover highlight
   */
  function hideHover() {
    currentHoverElement = null;
    if (hoverOverlay) {
      hoverOverlay.style.display = "none";
    }
  }

  /**
   * Selects an element (multi-select accumulates: clicking a selected one deselects it, the others are kept)
   */
  function selectElement(el) {
    if (!isSelectable(el)) return;

    // dataSourceId is injected at build time by jizao-source-loader; here it is only read and forwarded
    var dataSourceId = el.dataset.sourceId;

    // Already selected -> deselect
    if (selectedElements[dataSourceId]) {
      deselectElement(dataSourceId);
      return;
    }

    var container = getOverlayContainer();
    if (!container) return;

    var box = createHighlightBox("jizao-selected-box", el.tagName.toLowerCase());
    var rect = el.getBoundingClientRect();
    updateBoxPosition(box, rect);
    container.appendChild(box);

    selectedElements[dataSourceId] = {
      element: el,
      overlay: box,
    };

    var srcInfo = getSourceInfo(el);
    var msg = {
      source: "jizao-preview",
      type: "__jizao_element_selected",
      element: {
        dataSourceId: dataSourceId,
        tagName: el.tagName.toLowerCase(),
        className: getClassName(el),
        textContent: getTextContent(el),
        selector: generateSelector(el),
        boundingRect: {
          x: rect.left,
          y: rect.top,
          width: rect.width,
          height: rect.height,
        },
      },
    };

    if (srcInfo.sourceFile) msg.element.sourceFile = srcInfo.sourceFile;
    if (srcInfo.sourceLine != null) msg.element.sourceLine = srcInfo.sourceLine;
    if (srcInfo.sourceCol != null) msg.element.sourceCol = srcInfo.sourceCol;

    sendToParent(msg);
  }

  /**
   * Deselects one element
   */
  function deselectElement(dataSourceId) {
    var item = selectedElements[dataSourceId];
    if (!item) return;

    if (item.overlay && item.overlay.parentNode) {
      item.overlay.parentNode.removeChild(item.overlay);
    }
    delete selectedElements[dataSourceId];

    sendToParent({
      source: "jizao-preview",
      type: "__jizao_element_deselected",
      dataSourceId: dataSourceId,
    });
  }

  /**
   * Clears all selections
   */
  function clearSelection(sendEvent) {
    for (var id in selectedElements) {
      if (!selectedElements.hasOwnProperty(id)) continue;
      var item = selectedElements[id];
      if (item.overlay && item.overlay.parentNode) {
        item.overlay.parentNode.removeChild(item.overlay);
      }
    }
    selectedElements = {};

    if (sendEvent) {
      sendToParent({
        source: "jizao-preview",
        type: "__jizao_clear_selection",
      });
    }
  }

  /**
   * Repaints all highlight boxes (called on scroll/resize)
   */
  function repaintAll() {
    // Repaint the hover box
    if (hoverOverlay && currentHoverElement && currentHoverElement.parentNode) {
      var rect = currentHoverElement.getBoundingClientRect();
      updateBoxPosition(hoverOverlay, rect);
    }

    // Repaint all selection boxes
    for (var id in selectedElements) {
      if (!selectedElements.hasOwnProperty(id)) continue;
      var item = selectedElements[id];
      if (item.element && item.element.parentNode) {
        var r = item.element.getBoundingClientRect();
        updateBoxPosition(item.overlay, r);
      }
    }
  }

  var rafPending = false;
  function scheduleRepaint() {
    if (rafPending) return;
    rafPending = true;
    requestAnimationFrame(function () {
      rafPending = false;
      try {
        repaintAll();
      } catch (_e) {
        /* Swallow repaint errors */
      }
    });
  }

  // ========== Event handling ==========

  function handleMouseMove(e) {
    if (!isActive) return;
    try {
      var el = document.elementFromPoint(e.clientX, e.clientY);
      updateHover(el);
    } catch (_e) {
      /* Swallow mousemove errors */
    }
  }

  function handleClick(e) {
    if (!isActive) return;
    try {
      // Prevent default behavior and bubbling
      e.preventDefault();
      e.stopPropagation();

      var el = document.elementFromPoint(e.clientX, e.clientY);
      if (!isSelectable(el)) return;
      selectElement(el);
    } catch (_err) {
      /* Swallow click errors */
    }
  }

  function handleKeyDown(e) {
    if (!isActive) return;
    try {
      if (e.key === "Escape" || e.keyCode === 27) {
        clearSelection(true);
      }
    } catch (_e) {
      /* Swallow keydown errors */
    }
  }

  function handleScroll() {
    if (!isActive) return;
    scheduleRepaint();
  }

  /**
   * Mouse leaving the page: mouseleave does not bubble, so when document is the target it means leaving the whole page
   */
  function handleMouseLeave() {
    if (!isActive) return;
    hideHover();
  }

  /**
   * Window blur fallback: collapse the dashed box when the mouse moves straight from the iframe
   * to the parent page's toolbar, or when the window loses focus
   */
  function handleWindowBlur() {
    if (!isActive) return;
    hideHover();
  }

  function handleResize() {
    if (!isActive) return;
    scheduleRepaint();
  }

  /**
   * Receives messages from the parent page
   */
  function handleParentMessage(e) {
    try {
      // Verify origin
      if (e.origin !== parentOrigin) return;
      var data = e.data;
      if (!data || data.source !== "jizao-parent") return;

      if (data.type === "__jizao_toggle_select_mode") {
        setActive(!!data.enabled);
      } else if (data.type === "__jizao_clear_selection") {
        clearSelection(false);
      } else if (data.type === "__jizao_remove_selection") {
        if (data.dataSourceId) {
          deselectElement(data.dataSourceId);
        }
      }
    } catch (_e) {
      /* Swallow message handling errors */
    }
  }

  // ========== Mode switching ==========

  function setActive(enabled) {
    if (isActive === enabled) return;
    isActive = enabled;

    if (isActive) {
      // Entering active mode
      injectStyles();
      getOverlayContainer();

      document.addEventListener("mousemove", handleMouseMove, true);
      document.addEventListener("click", handleClick, true);
      document.addEventListener("keydown", handleKeyDown, true);
      // mouseleave / blur do not use capture: with capture we would receive every child
      // element's mouseleave and collapse the dashed box by mistake
      document.addEventListener("mouseleave", handleMouseLeave);
      window.addEventListener("blur", handleWindowBlur);
      window.addEventListener("scroll", handleScroll, true);
      window.addEventListener("resize", handleResize, true);
    } else {
      // Exiting active mode
      document.removeEventListener("mousemove", handleMouseMove, true);
      document.removeEventListener("click", handleClick, true);
      document.removeEventListener("keydown", handleKeyDown, true);
      document.removeEventListener("mouseleave", handleMouseLeave);
      window.removeEventListener("blur", handleWindowBlur);
      window.removeEventListener("scroll", handleScroll, true);
      window.removeEventListener("resize", handleResize, true);

      // Hide the hover highlight but keep the selection state (selection boxes stay visible
      // outside active mode per requirement; the parent page can clear them explicitly)
      hideHover();
    }
  }

  // ========== Initialization ==========

  try {
    window.addEventListener("message", handleParentMessage);
  } catch (_e) {
    /* Initialization failed, stay silent */
  }
})();
